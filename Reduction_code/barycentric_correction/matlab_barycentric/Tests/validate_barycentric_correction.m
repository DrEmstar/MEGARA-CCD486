function results=validate_barycentric_correction()
%VALIDATE_BARYCENTRIC_CORRECTION Regression against reference output.
%   Reference values were produced by the existing HRSP routines with
%   twelve decimal places instead of the normal three-place output.

target=["HD 209295";"HD 27274";"HIP 87937"; ...
    "HIP 24186";"HIP 32349";"HIP 54035"];
date=["2022-01-18";"2022-01-18";"2025-07-01"; ...
    "2025-07-01";"2025-07-01";"2025-07-01"];
time=["10:44:14.106";"10:44:14.106";"03:15:00"; ...
    "03:15:00";"03:15:00";"03:15:00"];
hrsp_total=[-2.401172574511;-9.552598534644;-4.138634374562; ...
    5.692993973676;-2.129036524172;-20.652020677305];
hrsp_orbital=[-2.273736345774;-9.468027978430;-4.389268401607; ...
    5.898596919012;-1.936727869170;-20.778879156139];
hrsp_rotation=[-0.127436228737;-0.084570556214;0.250634027045; ...
    -0.205602945336;-0.192308655002;0.126858478835];

matlab_total=zeros(size(target));
matlab_orbital=zeros(size(target));
matlab_rotation=zeros(size(target));
for row=1:numel(target)
    [matlab_total(row),details]=calculate_barycentric_correction( ...
        date(row),time(row),target(row));
    matlab_orbital(row)=details.orbital_correction;
    matlab_rotation(row)=details.rotational_correction;
end

results=table(target,date,time,hrsp_total,matlab_total, ...
    1000*(matlab_total-hrsp_total),hrsp_orbital,matlab_orbital, ...
    hrsp_rotation,matlab_rotation,'VariableNames', ...
    {'Target','Date','Time','HRSP_km_s','MATLAB_km_s','Difference_m_s', ...
    'HRSP_orbital_km_s','MATLAB_orbital_km_s', ...
    'HRSP_rotation_km_s','MATLAB_rotation_km_s'});
disp(results(:,1:6))
assert(max(abs(results.Difference_m_s))<1e-4, ...
    'MATLAB barycentric correction no longer agrees with HRSP reference values.');

%Each row contains aliases that HRSP resolves to one physical target.
alias_groups={{'HIP 32349','HD 48915','HR 2491','Alpha Canis Majoris', ...
    'Alp_CMa','9 CMa'}, ...
    {'HIP 91262','HD 172167','HR 7001','Alpha Lyrae','Alp Lyr','3 Lyr'}};
expected_hip=[32349,91262];
for group=1:numel(alias_groups)
    corrections=zeros(size(alias_groups{group}));
    for alias=1:numel(alias_groups{group})
        [star,identified]=find_barycentric_catalogue_target(alias_groups{group}{alias});
        assert(identified && star.hip==expected_hip(group), ...
            'Expanded HRSP target lookup failed for %s.',alias_groups{group}{alias});
        corrections(alias)=calculate_barycentric_correction( ...
            '2025-07-01','03:15:00',alias_groups{group}{alias});
    end
    assert(max(abs(corrections-corrections(1)))<1e-12, ...
        'Aliases for HIP %d do not produce identical corrections.',expected_hip(group));
end
end
